/**
 * Component Icon Vector đồ họa tương ứng với mã vật chứng
 */
export function ItemVectorIcon({ id, size = 36 }: { id?: string; size?: number }) {
  if (!id) return <ItemIconFolder size={size} />;
  if (id.includes('letter') || id.includes('thu')) return <ItemIconLetter size={size} />;
  if (id.includes('bookmark') || id.includes('sach')) return <ItemIconBookmark size={size} />;
  if (id.includes('handover') || id.includes('so')) return <ItemIconHandover size={size} />;
  if (id.includes('signature') || id.includes('ky')) return <ItemIconSignature size={size} />;
  if (id.includes('c1') || id.includes('names')) return <ItemIconStudentList size={size} />;
  if (id.includes('c2') || id.includes('classes')) return <ItemIconClasses size={size} />;
  if (id.includes('c3') || id.includes('shortlist')) return <ItemIconShortlist size={size} />;
  if (id.includes('quan') || id.includes('fixed')) return <ItemIconSqlDisk size={size} />;
  return <ItemIconFolder size={size} />;
}

